// Stage 1: take the lock, save registers, mmap() an RWX page, park on a
// `b .` it writes at the start of that page, publish the page address.
//
// The `b .` word is stored by this very thread and executed right after,
// so the instruction cache has to be told: `dc cvau` + `ic ivau` on that
// line. A bare `dsb; isb` is not enough on cores that keep separate
// instruction and data caches (seen on an Exynos 990: the fetch returned
// the page's old zeros and the target died with SIGILL at the page start).
inline std::vector<uint8_t> arm64_stage1_linjector_exact(uint64_t var_addr,
                                                         uint64_t alloc_len) {
  std::vector<uint8_t> sc = {
      0x86, 0x05, 0x00, 0x58, 0xc1, 0x7c, 0x5f, 0x08, 0xc1, 0xff, 0xff, 0x35,
      0x22, 0x00, 0x80, 0x52, 0xc2, 0x7c, 0x01, 0x08, 0x61, 0xff, 0xff, 0x35,
      0xff, 0x03, 0x04, 0xd1, 0xe0, 0x07, 0x00, 0xa9, 0xe2, 0x0f, 0x01, 0xa9,
      0xe4, 0x17, 0x02, 0xa9, 0xe6, 0x1f, 0x03, 0xa9, 0xe8, 0x27, 0x04, 0xa9,
      0xea, 0x2f, 0x05, 0xa9, 0xec, 0x37, 0x06, 0xa9, 0xee, 0x3f, 0x07, 0xa9,
      0xf0, 0x47, 0x08, 0xa9, 0xf2, 0x4f, 0x09, 0xa9, 0xf4, 0x57, 0x0a, 0xa9,
      0xf6, 0x5f, 0x0b, 0xa9, 0xf8, 0x67, 0x0c, 0xa9, 0xfa, 0x6f, 0x0d, 0xa9,
      0xfc, 0x77, 0x0e, 0xa9, 0xfe, 0x7f, 0x0f, 0xa9, 0x00, 0x00, 0x80, 0xd2,
      0x01, 0x14, 0x80, 0xd2, 0xe2, 0x00, 0x80, 0xd2, 0x43, 0x04, 0x80, 0xd2,
      0xe4, 0x03, 0x3f, 0xaa, 0x05, 0x00, 0x80, 0xd2, 0xc8, 0x1b, 0x80, 0xd2,
      0x01, 0x00, 0x00, 0xd4, // 120: svc #0            (mmap)
      0x21, 0x02, 0x00, 0x18, // 124: ldr w1, =`b .`    (literal at 192)
      0x01, 0x00, 0x00, 0xb9, // 128: str w1, [x0]
      0x20, 0x7b, 0x0b, 0xd5, // 132: dc  cvau, x0
      0x9f, 0x3b, 0x03, 0xd5, // 136: dsb ish
      0x20, 0x75, 0x0b, 0xd5, // 140: ic  ivau, x0
      0x9f, 0x3b, 0x03, 0xd5, // 144: dsb ish
      0xdf, 0x3f, 0x03, 0xd5, // 148: isb
      0x00, 0x00, 0x40, 0xb2, // 152: orr x0, x0, #1
      0xc0, 0x00, 0x00, 0xf9, // 156: str x0, [x6]      (publish page | 1)
      0x00, 0x00, 0x40, 0xd2, // 160: eor x0, x0, #1
      0x00, 0x00, 0x1f, 0xd6, // 164: br  x0
      0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, // 168: padding
      0x08, 0x5a, 0xe5, 0xa7, 0x75, 0x00, 0x00, 0x00, // 176: var_addr
      0xa0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // 184: alloc_len
      0x00, 0x00, 0x00, 0x14,                         // 192: `b .`
  };

  uint32_t mov_insn = 0xD2800001 | ((alloc_len & 0xFFFF) << 5);
  sc[96] = (mov_insn & 0xFF);
  sc[97] = ((mov_insn >> 8) & 0xFF);
  sc[98] = ((mov_insn >> 16) & 0xFF);
  sc[99] = ((mov_insn >> 24) & 0xFF);

  for (int i = 0; i < 8; i++) {
    sc[176 + i] = (var_addr >> (i * 8)) & 0xFF;
  }

  for (int i = 0; i < 8; i++) {
    sc[184 + i] = (alloc_len >> (i * 8)) & 0xFF;
  }

  return sc;
}

inline std::vector<uint8_t> arm64_infinite_loop() {
  return {0x00, 0x00, 0x00, 0x14};
}

