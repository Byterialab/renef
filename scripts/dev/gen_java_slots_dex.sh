#!/bin/sh
# Rebuilds src/agent/include/agent/slots_dex.h from
# src/agent/hook/java_slots/Slots.java (the helper class Java hooks keep
# their method copies in). Needs a JDK and d8 from the Android SDK
# build-tools; the generated header is checked in, so this only has to be
# run when Slots.java changes.
set -e
cd "$(dirname "$0")/../.."
D8=${D8:-$(ls "${ANDROID_HOME:-$HOME/Library/Android/sdk}"/build-tools/*/d8 2>/dev/null | sort | tail -1)}
[ -x "$D8" ] || { echo "d8 not found; set D8=/path/to/build-tools/<ver>/d8" >&2; exit 1; }
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
javac --release 11 -d "$TMP/classes" src/agent/hook/java_slots/Slots.java
"$D8" --release --min-api 26 --output "$TMP" "$TMP"/classes/com/renef/lab/Slots.class
OUT=src/agent/include/agent/slots_dex.h
{
  echo "// Generated by scripts/dev/gen_java_slots_dex.sh from"
  echo "// src/agent/hook/java_slots/Slots.java - do not edit."
  echo "#ifndef AGENT_SLOTS_DEX_H"
  echo "#define AGENT_SLOTS_DEX_H"
  echo "static const unsigned char slots_dex[] = {"
  od -An -v -tx1 "$TMP/classes.dex" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/  /'
  echo "};"
  echo "static const unsigned int slots_dex_len = $(wc -c < "$TMP/classes.dex" | tr -d ' ');"
  echo "#endif"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$TMP/classes.dex" | tr -d ' ') bytes of dex)"
